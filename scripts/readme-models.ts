/**
 * Regenerate the model table between the MODELS:START/END markers in README.md.
 *
 * The table is generated from `catalog.ts` + the dated FX rate in `models.ts`,
 * never hand-maintained: a hand-edited count or price is how a README starts
 * lying (references/testing.md § Phase 6, and the "139 vs 140" mismatch that was
 * caught only by cross-checking). Provenance markers are part of the data, so a
 * number that was advertised-but-not-measured keeps its † in the output.
 *
 * Usage: node scripts/readme-models.ts [--check]
 *   --check  exit non-zero if the README table is stale (used before committing)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG, EXCLUDED_MODEL_IDS, LONGCAT_VISION_CAVEAT, MIN_IMAGE_AREA_PX, thinkingLevelsFor } from "../catalog.ts";
import { CNY_RATE_DATE, DEFAULT_CNY_PER_USD, cnyToUsd } from "../models.ts";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const README = join(ROOT, "README.md");
const START = "<!-- MODELS:START (generated by scripts/readme-models.ts — do not edit between the markers) -->";
const END = "<!-- MODELS:END -->";

const rate = DEFAULT_CNY_PER_USD;
const usd = (cny: number) => `$${cnyToUsd(cny, rate).toFixed(6)}`;

const lines: string[] = [
  START,
  `| id | display name | context window | output cap | input | thinking | ¥/1M in · cached · out | $/1M in · cached · out |`,
  `|---|---|---|---|---|---|---|---|`,
];
for (const entry of CATALOG) {
  // A ‡ on the thinking column when the DEFAULT surface hides this model's off
  // switch — data-driven from the same selector models.ts uses, so the marker
  // cannot drift from the shipped map.
  const offHiddenOnDefault =
    entry.thinking.kind === "toggle" &&
    thinkingLevelsFor(entry.id, "openai-responses", entry.thinking.levels).off === null;
  lines.push(
    `| \`${entry.id}\` | ${entry.name} | ${entry.contextWindow.toLocaleString("en-US")} † | ` +
      `${entry.maxTokens.toLocaleString("en-US")} (measured) | ${entry.input.join(" + ")} | ` +
      `${entry.thinking.kind === "toggle" ? `on/off${offHiddenOnDefault ? "‡" : ""} (on by default)` : "none"} | ` +
      `${entry.cny.input} · ${entry.cny.cacheRead} · ${entry.cny.output} | ` +
      `${usd(entry.cny.input)} · ${usd(entry.cny.cacheRead)} · ${usd(entry.cny.output)} |`,
  );
}
lines.push(
  "",
  `† **Advertised, not independently measured.** Both machine-readable sources agree on`,
  `1 048 576 (\`GET /models\` → \`context_window\`, \`GET /models/{id}\` → \`context_length\`,`,
  `2026-10-10 and again 2026-11-07), but the free oracle is closed on this gateway: the \`max_tokens\``,
  `ceiling check fires before any context check, so measuring the window needs a ~1M-token prompt`,
  `(≈¥2 if accepted). That probe was **deliberately not run** — see "What is not verified".`,
  `Output caps have no † for the 2.5 family: they come from cap-oracle rejections that named the`,
  `ceiling (\`262145 … 262144\`; 2026-10-10, re-run 2026-10-24 and 2026-11-07). \`LongCat-2.0\` is`,
  `the exception and it is honest about it: its listing still advertises 131,072 while the`,
  `validator accepted 131,073 on 2026-11-07 and only rejects at 262,145 — the catalog keeps the`,
  `published clamp and records the contradiction in \`catalog.ts\`, because an accepted request`,
  `proves the validator gave way, not that the model emits 131,073 tokens.`,
  "",
  `‡ **Per-surface thinking control.** On the Responses surface the 2.5 family offers only`,
  `the positive level: NO token zeroes its reasoning there (measured 2026-10-24 on the Preview`,
  `— \`effort:"none"\` → 161 reasoning tokens — and re-measured 2026-11-07 on \`LongCat-2.5\`,`,
  `where \`effort:"none"\` → 23, no field → 13, \`effort:"low"\` → 18: one behaviour with noise on`,
  `top, not a scale), so pi hides \`off\` instead of selling a dead switch. \`off\` works for`,
  `LongCat-2.0 on Responses (\`effort:"none"\` → reasoning_tokens 0) and for all three ids on chat`,
  `(\`LONGCAT_SURFACE=chat\`, re-measured on LongCat-2.5 the same day: 0 reasoning tokens).`,
  `See [Thinking](#thinking).`,
  "",
  `USD columns are derived at the dated house rate ¥${rate} = $1 (${CNY_RATE_DATE}), overridable`,
  `per session with \`LONGCAT_CNY_PER_USD\`. The platform bills CNY; it also publishes a USD`,
  `column ($0.30 / $0.006 / $1.20) for its international site, and the machine-readable`,
  `\`pricing\` object matched the CNY column exactly — which is how the billing currency was`,
  `settled rather than assumed.`,
  "",
  `**Not registered** (each with its reason — \`EXCLUDED_MODEL_IDS\` in \`catalog.ts\` keeps them`,
  `out of the live overlay, so a refresh cannot re-add one):`,
  "",
  ...EXCLUDED_MODEL_IDS.map((id) => `- \`${id}\` — retired by the platform on 2026-05-29 (change log); absent from \`GET /models\` as of 2026-10-10.`),
  "",
  `Image notes for \`${CATALOG[0]!.id}\`: the gateway rejects an image whose area is ≤ ${MIN_IMAGE_AREA_PX} px²`,
  `(measured 2026-11-07: an 8×8 png → 400 "Image too small (area=64px), minimum required area: >200px";`,
  `196 px is still rejected and 225 px is accepted, so the bracket is closed — the floor was >256 px`,
  `on 2026-10-11 and relaxed since), and ${LONGCAT_VISION_CAVEAT}.`,
  "",
  `The gateway also advertises \`video\` input for \`LongCat-2.5\`, and it parses a \`video_url\` block`,
  `for real (a bogus url is rejected with 400 "Failed to download video from URL", measured 2026-11-07;`,
  `2.5-Preview parses the same block although its listing says text+image). It is not registered`,
  `because pi 1.5.0's \`ModelInputModality\` is exactly \`["text","image"]\` — there is no field value`,
  `that would let pi send a video, so claiming one would be a lie in the picker.`,
  END,
);

const table = lines.join("\n");
const current = readFileSync(README, "utf8");
const startIdx = current.indexOf(START.split(" (")[0]!);
const endIdx = current.indexOf(END);
if (startIdx === -1 || endIdx === -1) {
  console.error(`README.md is missing the marker comments:\n  ${START}\n  ${END}`);
  process.exit(2);
}
const next = current.slice(0, startIdx) + table + current.slice(endIdx + END.length);
if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("README model table is stale — run: node scripts/readme-models.ts");
    process.exit(1);
  }
  console.log("README model table is current.");
} else {
  writeFileSync(README, next);
  console.log(`README model table regenerated (${CATALOG.length} models, ${EXCLUDED_MODEL_IDS.length} excluded).`);
}
